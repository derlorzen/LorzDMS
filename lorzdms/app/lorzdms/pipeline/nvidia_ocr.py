"""NVIDIA Nemotron OCR v2 (multilingual default on NVIDIA NIM).

The hosted endpoint accepts images, not PDFs. Only pages requiring OCR are sent.
No searchable PDF derivative is generated by this API.
"""
from __future__ import annotations

import base64
import io
import time
from pathlib import Path

import httpx
from PIL import Image, ImageOps, ImageSequence

from .. import appsettings, crypto
from ..google import http as ghttp
from .text import MIN_CHARS_PER_PAGE, OcrFailed, TextResult, extract_embedded, needs_ocr

ENDPOINT = "https://ai.api.nvidia.com/v1/cv/nvidia/nemotron-ocr-v2"
MODEL = "nvidia/nemotron-ocr-v2"
VARIANT = "multilingual"
MAX_SIDE = 3500
MAX_JPEG_BYTES = 3 * 1024 * 1024


def _image_url(image: Image.Image) -> str:
    rgb = ImageOps.exif_transpose(image).convert("RGB")
    rgb.thumbnail((MAX_SIDE, MAX_SIDE))
    # Keep individual requests bounded, including for large/color scans.
    while True:
        buf = io.BytesIO()
        rgb.save(buf, format="JPEG", quality=90)
        if buf.tell() <= MAX_JPEG_BYTES:
            return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")
        rgb.thumbnail((max(1, int(rgb.width * 0.8)), max(1, int(rgb.height * 0.8))))


def _recognize(client: httpx.Client, image: Image.Image, deadline: float) -> str:
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise OcrFailed("NVIDIA OCR: Zeitlimit überschritten")
    try:
        response = client.post(
            ENDPOINT,
            json={"input": [{"type": "image_url", "url": _image_url(image)}],
                  "merge_levels": ["paragraph"]},
            timeout=remaining,
        )
        response.raise_for_status()
        data = response.json()["data"]
        if len(data) != 1 or data[0].get("index", 0) != 0:
            raise ValueError("unexpected page count")
        texts = [d["text_prediction"]["text"] for d in data[0]["text_detections"]]
        if not all(isinstance(t, str) for t in texts):
            raise ValueError("invalid text")
        return "\n".join(t.strip() for t in texts if t.strip())
    except httpx.HTTPStatusError as exc:
        raise OcrFailed(f"NVIDIA OCR: HTTP {exc.response.status_code}") from exc
    except httpx.RequestError as exc:
        raise OcrFailed(f"NVIDIA OCR: Verbindungsfehler ({type(exc).__name__})") from exc
    except (ValueError, KeyError, TypeError, IndexError, AttributeError) as exc:
        raise OcrFailed("NVIDIA OCR: ungültiges Antwortformat") from exc


def extract(path: Path, mime: str, *, timeout: int, force_ocr: bool = False) -> TextResult:
    is_image = mime.startswith("image/")
    embedded = [] if is_image else extract_embedded(path)
    if not is_image and not force_ocr and not needs_ocr(embedded):
        return TextResult("\n\f\n".join(embedded), embedded, "embedded", len(embedded))
    if appsettings.get("allow_external_ocr") is not True:
        raise OcrFailed("NVIDIA OCR: externe OCR nicht freigegeben")
    key = crypto.get_secret("ocr_api_key")
    if not key:
        raise OcrFailed("NVIDIA OCR: API-Key fehlt")
    started = time.monotonic()
    deadline = started + timeout
    pages: list[str] = []
    used_ocr = False
    kept_embedded = False

    def process(image: Image.Image, original: str = "") -> None:
        nonlocal used_ocr, kept_embedded
        recognized = _recognize(client, image, deadline)
        if recognized and (force_ocr or len(recognized.strip()) > len(original.strip())):
            pages.append(recognized)
            used_ocr = True
        else:
            pages.append(original)
            kept_embedded |= bool(original.strip())

    with httpx.Client(transport=ghttp._transport, follow_redirects=False, trust_env=False,
                      headers={"Authorization": f"Bearer {key}", "Accept": "application/json"}) as client:
        if is_image:
            with Image.open(path) as image:
                for frame in ImageSequence.Iterator(image):
                    process(frame)
        else:
            import pypdfium2 as pdfium
            pdf = pdfium.PdfDocument(str(path))
            try:
                for i, original in enumerate(embedded):
                    if not force_ocr and len(original.strip()) >= MIN_CHARS_PER_PAGE:
                        pages.append(original)
                        kept_embedded = True
                        continue
                    page = pdf[i]
                    try:
                        scale = min(300 / 72, MAX_SIDE / max(page.get_size()))
                        bitmap = page.render(scale=scale)
                        try:
                            process(bitmap.to_pil(), original)
                        finally:
                            bitmap.close()
                    finally:
                        page.close()
            finally:
                pdf.close()
    method = ("mixed" if kept_embedded else "ocr") if used_ocr else ("embedded" if kept_embedded else "none")
    warnings = [] if any(p.strip() for p in pages) else ["NVIDIA OCR: kein Text erkannt"]
    return TextResult("\n\f\n".join(pages), pages, method, len(pages), ocr_used=used_ocr,
                      ocr_seconds=time.monotonic() - started, warnings=warnings)
